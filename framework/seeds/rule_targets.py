# idempotent queries; re-executing UPDATE/DELETE changes table state and
# self-produces differences. A DML oracle must snapshot/compare state, not
# replay the same statement.



def as_seeds() -> list[dict]:
    """Emit corpus-format seed dicts."""
    out = []
    for i, (rule, setup, query, note) in enumerate(RULE_TEMPLATES + FEATURE_TEMPLATES):
        out.append({
            "setup_sqls": list(setup),
            "query": query,
            "source": f"rule_target:{rule}#{i}",
            "engine": "duckdb",
            "tags": ["rule_target", rule, note],
        })
    return out
