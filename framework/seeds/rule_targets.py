"""Per-rule trigger templates: queries designed to exercise each optimizer
rule — i.e. each *optimization direction* — on the current engine.

Rationale: novel bugs live in the product space (existing complex
queries) x (newer optimizer features). Old corpus queries predate rules
added in 1.4/1.5.x; per-rule targeted queries close that gap. Each
template is a Seed-like dict {setup_sqls, query, source, tags} so it can
flow through the same corpus_hunt pipeline; sigma then attributes any
hit to a specific rule = a specific optimization direction.

Data variety matters more than query cleverness: each template should be
tried under several data shapes (empty side, NULL keys, skewed, dup
rows) — the mutator's structural variants and DCE handle the rest.
"""

