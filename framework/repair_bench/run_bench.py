"""R1 repair benchmark — does Hunter's diagnostic output make the Fixer better?

Three input tiers for the same patch task on the same buggy source:
  (a) raw      — one observed divergence (query, actual, expected)
  (b) repro    — (a) + full minimized reproducer set with observed/expected
  (c) diag     — (b) + diagnosis bundle (mechanism hypothesis + behavior contract,
                 generated by an LLM diagnosis call on the reproducer table)

Each attempt: LLM emits a unified diff -> apply -> gcc build -> run
reproducers + sanity battery -> score. One retry allowed when the diff
fails to apply or the build fails (a real agent gets feedback).

Usage:
  python3 run_bench.py --case sqlite_c --attempts 3
"""
from __future__ import annotations

import argparse
import json
import logging
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from util.paths import KEYS_YML  # noqa: E402

HERE = Path(__file__).resolve().parent
SRC = HERE / "src_pristine"
RUNS = HERE / "runs"

LOGGER = logging.getLogger("repair_bench")
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")

BUILD_CMD = [
    "gcc", "-O2", "-o", "sqlite3", "sqlite3.c", "shell.c",
    "-lpthread", "-ldl", "-lm",
]


def load_key() -> tuple[str, str]:
    txt = KEYS_YML.read_text()
    key = re.search(r"key:\s*[\"']?([^\s\"']+)", txt).group(1)
    url = re.search(r"completion_url:\s*[\"']?([^\s\"']+)", txt).group(1)
    return key, url.rstrip("/")


def call_llm(prompt: str, key: str, base: str, max_tokens: int = 6000) -> str:
    r = httpx.post(
        f"{base}/chat/completions",
        headers={"Authorization": f"Bearer {key}"},
        json={
            "model": "deepseek-chat",
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.6,
            "max_tokens": max_tokens,
        },
        timeout=300.0,
    )
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"]


def run_sql(binpath: Path, sql: str) -> tuple[int, str, str]:
    p = subprocess.run(
        [str(binpath), "-bail", ":memory:", sql],
        capture_output=True, timeout=20,
    )
    # patched binaries may emit invalid UTF-8 (that is the bug class)
    return (p.returncode,
            p.stdout.decode("utf-8", "replace").strip(),
            p.stderr.decode("utf-8", "replace").strip())


def eval_bin(binpath: Path, cases: list[tuple[str, str, str]]) -> dict:
    """cases: (name, sql, expected). expected '!ERROR' => nonzero exit."""
    passed, detail = 0, []
    for name, sql, expected in cases:
        rc, out, err = run_sql(binpath, sql)
        if expected == "!ERROR":
            ok = rc != 0 or "error" in (out + err).lower()
            got = out or err.splitlines()[-1] if err else out
        else:
            ok = rc == 0 and out == expected
            got = out if rc == 0 else f"rc={rc} {err[:80]}"
        passed += ok
        detail.append({"name": name, "ok": ok, "got": got, "want": expected})
    return {"passed": passed, "total": len(cases), "detail": detail}


def load_cases(path: Path) -> list[tuple[str, str, str]]:
    rows = []
    for line in path.read_text().splitlines():
        if line.strip():
            rows.append(tuple(line.split("\t")))
    return rows


def observed_table(binpath: Path, repro: list[tuple[str, str, str]]) -> str:
    lines = ["case | query | actual (buggy) | expected"]
    for name, sql, want in repro:
        rc, out, err = run_sql(binpath, sql)
        got = out if rc == 0 else f"ERROR: {err.splitlines()[-1] if err else rc}"
        lines.append(f"{name} | {sql} | {got} | {want}")
    return "\n".join(lines)


def extract_funcs(text: str) -> dict[str, str]:
    """Parse `### FUNC name ... ### END` complete-function blocks."""
    out = {}
    for m in re.finditer(
            r"###\s*FUNC\s+([A-Za-z_][A-Za-z0-9_]*)\s*\n(.*?)###\s*END",
            text, re.S):
        body = m.group(2)
        body = re.sub(r"^```[a-z]*\n|```$", "", body.strip(),
                      flags=re.M).strip()
        out[m.group(1)] = body + "\n"
    return out


def splice_func(src: str, name: str, body: str) -> str | None:
    """Replace the definition of `name` in sqlite3.c text with `body`.

    Definitions sit at column 0; the function ends at the next `}` at
    column 0. Unknown names are inserted before unistrFunc.
    """
    lines = src.splitlines(keepends=True)
    start = None
    pat = re.compile(rf"^(?:static|SQLITE_PRIVATE|SQLITE_API)\b[^;]*\b"
                     rf"{re.escape(name)}\s*\(")
    for i, ln in enumerate(lines):
        if not pat.match(ln):
            continue
        # skip prototypes: `;` at paren-depth-0 before `{` => declaration
        depth_p, proto, isdef = 0, False, False
        for j in range(i, min(i + 15, len(lines))):
            for ch in lines[j]:
                if ch == "(":
                    depth_p += 1
                elif ch == ")":
                    depth_p -= 1
                elif depth_p == 0 and ch == ";":
                    proto = True
                elif depth_p == 0 and ch == "{":
                    isdef = True
                if proto or isdef:
                    break
            if proto or isdef:
                break
        if proto or not isdef:
            continue
        start = i
        break
    if start is None:
        # new helper: insert before unistrFunc's comment block
        for i, ln in enumerate(lines):
            if ln.startswith("static void unistrFunc("):
                start = i
                while start > 0 and not lines[start - 1].startswith("/*"):
                    start -= 1
                while start > 0 and lines[start - 1].startswith(("*", "/*")):
                    start -= 1
                return "".join(lines[:start]) + body + "\n" + "".join(lines[start:])
        return None
    end = None
    for i in range(start + 1, len(lines)):
        if lines[i].startswith("}"):  # SQLite style: closing brace at col 0
            end = i + 1
            break
    if end is None:
        return None
    return "".join(lines[:start]) + body + "".join(lines[end:])


def build_prompt(case_dir: Path, tier: str, obs_table: str, diag: str) -> str:
    code = (case_dir / "code_excerpt.c").read_text()
    repro = load_cases(case_dir / "reproducers.tsv")
    first = repro[0]
    head = (
        "You are fixing a bug in SQLite 3.51.2. The relevant excerpt of "
        "sqlite3.c is below (isNHex, unistrFunc, sqlite3AppendOneUtf8Character).\n"
        "Emit the COMPLETE corrected text of every function you change, each "
        "wrapped exactly as:\n### FUNC <name>\n<full C function text>\n### END\n"
        "New helper functions use the same wrapper (they will be inserted "
        "before unistrFunc). No prose, no diffs.\n\n```c\n"
        + code + "\n```\n\n"
    )
    if tier == "a_raw":
        head += (
            f"Bug report: `{first[1]}` outputs `{run_sql_baseline(first[1])}` "
            f"but should output `{first[2]}`. Fix it.\n"
        )
    else:
        head += (
            "Observed (buggy) vs expected behavior on this build:\n"
            + obs_table + "\nFix all failing cases.\n"
        )
        if tier == "c_diag":
            head += "\n## Diagnosis from the analysis agent\n" + diag + "\n"
    return head


_BASELINE = {}


def run_sql_baseline(sql: str) -> str:
    if not _BASELINE:
        pass
    return _BASELINE.get(sql, "?")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", default="sqlite_c")
    ap.add_argument("--attempts", type=int, default=3)
    ap.add_argument("--tiers", default="a_raw,b_repro,c_diag")
    args = ap.parse_args()

    case_dir = HERE / "cases" / args.case
    repro = load_cases(case_dir / "reproducers.tsv")
    sanity = load_cases(case_dir / "sanity.tsv")
    key, base = load_key()

    # pristine baseline build for observed values
    base_dir = RUNS / "_baseline"
    if not (base_dir / "sqlite3").exists():
        base_dir.mkdir(parents=True, exist_ok=True)
        for f in SRC.iterdir():
            shutil.copy2(f, base_dir / f.name)
        LOGGER.info("building pristine baseline...")
        subprocess.run(BUILD_CMD, cwd=base_dir, check=True, timeout=600)
    for _, sql, _ in repro:
        rc, out, err = run_sql(base_dir / "sqlite3", sql)
        _BASELINE[sql] = out if rc == 0 else f"ERROR: {err[:60]}"
    obs = observed_table(base_dir / "sqlite3", repro)
    (RUNS / "observed_table.txt").write_text(obs)
    LOGGER.info("observed table:\n%s", obs)

    # one diagnosis call, reused across c_diag attempts (like the Fixer
    # producing one diagnosis artifact per family)
    diag = ""
    diag_cache = RUNS / f"diagnosis_{args.case}.txt"
    if "c_diag" in args.tiers:
        if diag_cache.exists():
            diag = diag_cache.read_text()
        else:
            d_prompt = (
                "These are observed vs expected results for unistr() on SQLite "
                "3.51.2. The function is documented as a work-alike of "
                "PostgreSQL's unistr().\n\n" + obs + "\n\n"
                "Hypothesize the root-cause mechanism in the escape decoder "
                "and state the complete correct behavioral contract (pairing "
                "rules, error cases). Be specific and terse."
            )
            diag = call_llm(d_prompt, key, base)
            diag_cache.write_text(diag)
            LOGGER.info("diagnosis:\n%s", diag)

    results_path = RUNS / f"results_{args.case}.jsonl"
    for tier in args.tiers.split(","):
        for k in range(args.attempts):
            tag = f"{tier}_{k}"
            adir = RUNS / tag
            if adir.exists():
                shutil.rmtree(adir)
            adir.mkdir(parents=True)
            for f in SRC.iterdir():
                shutil.copy2(f, adir / f.name)

            rec = {"case": args.case, "tier": tier, "attempt": k,
                   "llm_calls": 0, "apply_ok": False, "build_ok": False,
                   "repro_pass": 0, "repro_total": len(repro),
                   "sanity_pass": 0, "sanity_total": len(sanity),
                   "t_patch": None, "error": None}
            prompt = build_prompt(case_dir, tier, obs, diag)
            (adir / "prompt.txt").write_text(prompt)
            t0 = time.time()
            for retry in range(2):
                try:
                    resp = call_llm(prompt, key, base)
                except Exception as e:  # noqa: BLE001
                    rec["error"] = f"llm: {e}"
                    break
                rec["llm_calls"] += 1
                (adir / f"resp_{retry}.txt").write_text(resp)
                funcs = extract_funcs(resp)
                if not funcs:
                    rec["error"] = "no ### FUNC blocks in response"
                    prompt += ("\n\nYour previous reply had no `### FUNC name`"
                               " blocks. Emit ONLY complete functions in that"
                               " wrapper.")
                    continue
                for f in SRC.iterdir():  # restore pristine before splice
                    shutil.copy2(f, adir / f.name)
                src_text = (adir / "sqlite3.c").read_text()
                failed = []
                for fname, fbody in funcs.items():
                    new_text = splice_func(src_text, fname, fbody)
                    if new_text is None:
                        failed.append(fname)
                    else:
                        src_text = new_text
                if failed:
                    rec["error"] = f"splice failed: {failed}"
                    prompt += (f"\n\nFunctions {failed} could not be spliced. "
                               "Emit ONLY complete `### FUNC` blocks.")
                    continue
                (adir / "spliced_funcs.txt").write_text("\n".join(funcs))
                # structural gate: preprocessor structure must be intact
                p0 = (adir / "sqlite3.c").read_text()
                if (src_text.count("\n#if") != p0.count("\n#if")
                        or src_text.count("\n#endif") != p0.count("\n#endif")):
                    rec["error"] = "splice broke preprocessor structure"
                    continue
                (adir / "sqlite3.c").write_text(src_text)
                rec["apply_ok"] = True
                b = subprocess.run(
                    BUILD_CMD, cwd=adir, capture_output=True, text=True,
                    timeout=600,
                )
                (adir / "build.log").write_text(b.stdout + b.stderr)
                if b.returncode != 0:
                    rec["error"] = f"build: {b.stderr[-300:]}"
                    prompt += f"\n\nPatch applied but build failed:\n{b.stderr[-800:]}\nEmit a corrected unified diff ONLY."
                    continue
                rec["build_ok"] = True
                r_eval = eval_bin(adir / "sqlite3", repro)
                s_eval = eval_bin(adir / "sqlite3", sanity)
                rec["repro_pass"] = r_eval["passed"]
                rec["sanity_pass"] = s_eval["passed"]
                (adir / "eval.json").write_text(
                    json.dumps({"repro": r_eval, "sanity": s_eval}, indent=2)
                )
                break
            rec["t_patch"] = round(time.time() - t0, 1)
            with results_path.open("a") as f:
                f.write(json.dumps(rec) + "\n")
            LOGGER.info(
                "%s: apply=%s build=%s repro=%d/%d sanity=%d/%d calls=%d %s",
                tag, rec["apply_ok"], rec["build_ok"], rec["repro_pass"],
                rec["repro_total"], rec["sanity_pass"], rec["sanity_total"],
                rec["llm_calls"], rec["error"] or "",
            )
    LOGGER.info("done -> %s", results_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
